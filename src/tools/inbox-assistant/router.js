'use strict';
const express = require('express');
const router = express.Router();
const verifyShopifySession = require('../../middleware/verifyShopifySession');
const { requireCreditsOnMutation } = require('../../core/creditMiddleware');
const ah = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
router.use(verifyShopifySession);
const engine = require('./engines/inbox-engine');
router.get('/health', ah(async (req, res) => res.json({ ok: true, service: 'inbox-assistant', v: '2.0.0' })));
router.get('/dashboard', ah(async (req, res) => res.json({ ok: true, ...engine.getDashboardStats() })));
router.get('/canned-responses', ah(async (req, res) => res.json({ ok: true, cannedResponses: engine.getCannedResponses() })));
router.get('/conversations', ah(async (req, res) => res.json({ ok: true, ...engine.getConversations(req.query) })));
router.get('/conversations/:id', ah(async (req, res) => { const item = engine.getConversation(req.params.id); if (!item) return res.status(404).json({ ok: false, error: 'not found' }); res.json({ ok: true, conversation: item }); }));
router.post('/reply/suggest', requireCreditsOnMutation('email-gen'), ah(async (req, res) => res.json({ ok: true, ...engine.suggestReply(req.body) })));
router.post('/classify-intent', ah(async (req, res) => res.json({ ok: true, ...engine.classifyIntent(req.body) })));
router.use((err, req, res, next) => res.status(500).json({ ok: false, error: err.message }));
module.exports = router;
