'use strict';
const express = require('express');
const router = express.Router();
const verifyShopifySession = require('../../middleware/verifyShopifySession');
const { requireCreditsOnMutation } = require('../../core/creditMiddleware');
const engine = require('./engines/inbox-engine');
router.use(verifyShopifySession);
const ah = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
router.get('/health', ah(async (req, res) => res.json({ ok: true, service: 'inbox-assistant', v: '2.0.0' })));
router.get('/dashboard', ah(async (req, res) => res.json({ ok: true, ...engine.getDashboardStats() })));
router.get('/conversations', ah(async (req, res) => res.json({ ok: true, conversations: engine.getConversations(req.query) })));
router.get('/conversations/:id', ah(async (req, res) => { const c = engine.getConversation(req.params.id); if (!c) return res.status(404).json({ ok: false, error: 'not found' }); res.json({ ok: true, conversation: c }); }));
router.get('/canned-responses', ah(async (req, res) => res.json({ ok: true, responses: engine.getCannedResponses() })));
router.post('/conversations/:id/suggest-reply', requireCreditsOnMutation('email-gen'), ah(async (req, res) => res.json({ ok: true, ...engine.suggestReply(req.params.id) })));
router.post('/classify', ah(async (req, res) => { if (!req.body.message) return res.status(400).json({ ok: false, error: 'message required' }); res.json({ ok: true, ...engine.classifyIntent(req.body.message) }); }));
router.use((err, req, res, next) => res.status(500).json({ ok: false, error: err.message }));
module.exports = router;
