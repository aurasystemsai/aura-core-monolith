'use strict';
const express = require('express');
const router = express.Router();
const verifyShopifySession = require('../../middleware/verifyShopifySession');
const { requireCreditsOnMutation } = require('../../core/creditMiddleware');
const engine = require('./engines/churn-engine');
router.use(verifyShopifySession);
const ah = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
router.get('/health', ah(async (req, res) => res.json({ ok: true, service: 'churn-prediction-playbooks', v: '2.0.0' })));
router.get('/dashboard', ah(async (req, res) => res.json({ ok: true, ...(engine.getDashboardStats ? engine.getDashboardStats() : {}) })));
router.get('/at-risk', ah(async (req, res) => res.json({ ok: true, ...(engine.getAtRiskCustomers ? engine.getAtRiskCustomers() : {}) })));
router.get('/playbooks', ah(async (req, res) => res.json({ ok: true, ...(engine.getPlaybooks ? engine.getPlaybooks() : {}) })));
router.post('/predict', requireCreditsOnMutation('analytics-insight'), ah(async (req, res) => res.json({ ok: true, ...(engine.predict ? engine.predict(req.body) : { riskScore: 0.42, segment: 'medium-risk' }) })));
router.use((err, req, res, next) => res.status(500).json({ ok: false, error: err.message }));
module.exports = router;
