'use strict';
const express = require('express');
const router = express.Router();
const verifyShopifySession = require('../../middleware/verifyShopifySession');
const { requireCreditsOnMutation } = require('../../core/creditMiddleware');
const ah = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);
router.use(verifyShopifySession);
router.get('/health', ah(async (req, res) => res.json({ ok: true, service: 'churn-prediction-playbooks', v: '2.0.0' })));
const engine = require('./engines/churn-engine');
router.get('/dashboard', ah(async (req, res) => res.json({ ok: true, ...engine.getChurnSummary() })));
router.get('/segments', ah(async (req, res) => res.json({ ok: true, segments: engine.getSegments() })));
router.get('/playbooks', ah(async (req, res) => res.json({ ok: true, playbooks: engine.getPlaybooks() })));
router.get('/cohorts', ah(async (req, res) => res.json({ ok: true, cohorts: engine.getCohortRetention() })));
router.get('/warnings', ah(async (req, res) => res.json({ ok: true, warnings: engine.getEarlyWarnings() })));
router.post('/predict', requireCreditsOnMutation('analytics-insight'), ah(async (req, res) => { const { customerId, rfmScore } = req.body; if (!customerId) return res.status(400).json({ ok: false, error: 'customerId required' }); res.json({ ok: true, ...engine.calcChurnProbability(customerId, rfmScore || 8) }); }));
router.post('/roi', requireCreditsOnMutation('analytics-insight'), ah(async (req, res) => { const { segment, campaignCost = 1000, revenuePerCustomer = 180 } = req.body; if (!segment) return res.status(400).json({ ok: false, error: 'segment required' }); res.json({ ok: true, ...engine.calcReactivationRoi(segment, campaignCost, revenuePerCustomer) }); }));
router.use((err, req, res, next) => res.status(500).json({ ok: false, error: err.message }));
module.exports = router;
